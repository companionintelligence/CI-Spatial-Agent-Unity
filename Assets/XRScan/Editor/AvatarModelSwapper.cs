using System.Linq;
using System.Text;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using XRScan.Avatar;

namespace XRScan.EditorTools
{
    /// <summary>
    /// Swaps the 3D model behind the scene's avatar while keeping everything that makes it an
    /// avatar: the behaviour components on the model's root (<see cref="AvatarLoadController"/>,
    /// <see cref="GazeController"/>, <see cref="AvatarLipSync"/>, the TTS + its AudioSource) and every
    /// scene reference to them (AppBootstrap, AvatarPerceptionBridge). It replaces the prefab asset
    /// of the avatar's model instance in place (<see cref="PrefabUtility.ReplacePrefabAssetOfPrefabInstance(GameObject, GameObject, PrefabReplacingSettings, InteractionMode)"/>),
    /// then re-binds the model-specific references — the root transform and the face (and, if the
    /// model has one, teeth) renderer that lip-sync drives. Idempotent. Applies to the app scene and to
    /// the in-Editor development scene with the mock wiring, which carries the same avatar.
    /// Menu: <b>XRScan &gt; Scene &gt; Use CI Companion avatar</b>; headless:
    /// <c>-executeMethod XRScan.EditorTools.AvatarModelSwapper.UseCompanionAvatar</c>.
    /// </summary>
    public static class AvatarModelSwapper
    {
        public const string ScenePath = "Assets/XRScan/App/Scenes/XRScan_Main.unity";
        public const string DevScenePath = "Assets/XRScan/App/Scenes/XRScan_Dev.unity";

        /// <summary>Every scene with an avatar that <see cref="UseCompanionAvatar"/> updates.</summary>
        public static readonly string[] AvatarScenes = { ScenePath, DevScenePath };

        /// <summary>The CI-owned avatar generated by <c>tools/avatar/build_ci_companion.py</c>.</summary>
        public const string CompanionModelPath = "Assets/XRScan/Avatar/Models/CI_Companion.glb";
        public const string CompanionAvatarName = "Avatar (CI Companion)";

        [MenuItem("XRScan/Scene/Use CI Companion avatar", false, 44)]
        public static void UseCompanionAvatar()
        {
            bool ok = true;
            foreach (var scenePath in AvatarScenes)
            {
                if (AssetDatabase.LoadAssetAtPath<SceneAsset>(scenePath) == null) continue;
                ok &= SwapSceneAvatar(CompanionModelPath, CompanionAvatarName, scenePath);
            }
            if (!ok && Application.isBatchMode) EditorApplication.Exit(1);
        }

        /// <summary>Swaps the avatar model in the app scene (<see cref="ScenePath"/>).</summary>
        public static bool SwapSceneAvatar(string modelPath, string avatarName) =>
            SwapSceneAvatar(modelPath, avatarName, ScenePath);

        /// <summary>
        /// Points the avatar in <paramref name="scenePath"/> (the GameObject carrying
        /// <see cref="AvatarLoadController"/>) at the model at <paramref name="modelPath"/>, renames it,
        /// re-binds its references and saves the scene.
        /// </summary>
        public static bool SwapSceneAvatar(string modelPath, string avatarName, string scenePath)
        {
            var model = AssetDatabase.LoadAssetAtPath<GameObject>(modelPath);
            if (model == null)
            {
                Debug.LogError($"[AvatarModelSwapper] No model at {modelPath} (is it imported?).");
                return false;
            }

            var scene = EditorSceneManager.OpenScene(scenePath, OpenSceneMode.Single);
            var avatar = FindAvatar();
            if (avatar == null)
            {
                Debug.LogError($"[AvatarModelSwapper] No AvatarLoadController in {scenePath}.");
                return false;
            }
            if (!PrefabUtility.IsPartOfPrefabInstance(avatar) || PrefabUtility.GetOutermostPrefabInstanceRoot(avatar) != avatar)
            {
                Debug.LogError($"[AvatarModelSwapper] '{avatar.name}' is not the root of a model instance; nothing to swap.");
                return false;
            }

            var previous = PrefabUtility.GetCorrespondingObjectFromSource(avatar);
            var previousPath = previous != null ? AssetDatabase.GetAssetPath(previous) : "<missing>";
            if (previous != model)
            {
                var settings = new PrefabReplacingSettings
                {
                    changeRootNameToAssetName = false,
                    // Same-named nodes (e.g. a shared skeleton) keep their overrides; references to
                    // nodes the new model lacks are cleared and re-bound below.
                    objectMatchMode = ObjectMatchMode.ByHierarchy,
                    // Drop the old model's property overrides (blend-shape weights on meshes that no
                    // longer exist, the name); keep the placement and the added behaviour components.
                    prefabOverridesOptions = PrefabOverridesOptions.ClearNonDefaultPropertyOverrides,
                    logInfo = true,
                };
                PrefabUtility.ReplacePrefabAssetOfPrefabInstance(avatar, model, settings, InteractionMode.AutomatedAction);
                avatar = FindAvatar();
            }

            avatar.name = avatarName;
            var root = avatar.transform;
            var face = AvatarLoadController.FindFaceRenderer(root);
            var teeth = root.GetComponentsInChildren<SkinnedMeshRenderer>(true)
                .FirstOrDefault(r => r != face && r.name.ToLowerInvariant().Contains("teeth") &&
                                     r.sharedMesh != null && r.sharedMesh.blendShapeCount > 0);

            SetRef(avatar.GetComponent<AvatarLoadController>(), "avatarRoot", root);
            SetRef(avatar.GetComponent<GazeController>(), "body", root);
            var lipSync = avatar.GetComponent<AvatarLipSync>();
            SetRef(lipSync, "faceRenderer", face);
            SetRef(lipSync, "teethRenderer", teeth);

            EditorSceneManager.MarkSceneDirty(scene);
            if (!EditorSceneManager.SaveScene(scene, scenePath))
            {
                Debug.LogError($"[AvatarModelSwapper] Saving {scenePath} failed.");
                return false;
            }

            var sb = new StringBuilder();
            sb.AppendLine($"[AvatarModelSwapper] {scenePath}: '{avatarName}': {previousPath} -> {modelPath}");
            sb.AppendLine($"  face renderer: {(face != null ? face.name : "<none>")}, teeth renderer: {(teeth != null ? teeth.name : "<none>")}");
            if (face != null && face.sharedMesh != null)
            {
                var mesh = face.sharedMesh;
                var missing = AvatarLipSync.VisemeBlendShapes.Where(v => mesh.GetBlendShapeIndex(v) < 0).ToArray();
                sb.AppendLine($"  {mesh.blendShapeCount} blend shapes; lip-sync visemes missing: {(missing.Length == 0 ? "none" : string.Join(", ", missing))}");
            }
            Debug.Log(sb.ToString());
            return face != null;
        }

        private static GameObject FindAvatar()
        {
            var loader = Object.FindAnyObjectByType<AvatarLoadController>(FindObjectsInactive.Include);
            return loader != null ? loader.gameObject : null;
        }

        private static void SetRef(Object target, string property, Object value)
        {
            if (target == null) return;
            var so = new SerializedObject(target);
            var prop = so.FindProperty(property);
            if (prop == null)
            {
                Debug.LogError($"[AvatarModelSwapper] Property '{property}' not found on {target.GetType().Name}.");
                return;
            }
            prop.objectReferenceValue = value;
            so.ApplyModifiedPropertiesWithoutUndo();
        }
    }
}
